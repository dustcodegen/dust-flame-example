import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../tool/generate.dart';

void main() {
  test('discovers annotated classes and emits stable typed Flame helpers', () {
    const source = '''
@ViewModel(state: State)
class ZebraViewModel {
  ZebraViewModel({int optional = 1});
}
// @ViewModel must not register this class.
class IgnoredViewModel {}
@state.ViewModel(state: State)
class AppleViewModel {}
''';
    final output = generateBindings(source);
    expect(output, generateBindings(source));
    expect(
      output,
      contains('const _appleViewModelKey = ViewModelKey(AppleViewModel.new);'),
    );
    expect(output, contains('AppleViewModel readAppleViewModel()'));
    expect(
      output,
      contains(
        'void watchAppleViewModel(void Function(AppleViewModel) callback)',
      ),
    );
    expect(output, contains('watchViewModel(_appleViewModelKey, callback)'));
    expect(output, isNot(contains('IgnoredViewModel')));
    expect(
      output.indexOf('_appleViewModelKey'),
      lessThan(output.indexOf('_zebraViewModelKey')),
    );
  });

  test('longer model names emit stable readable forwarders', () {
    final output = generateBindings(
      '@ViewModel(state: State) class ChallengeViewModel {}',
    );
    expect(output, '''// Generated by tool/generate.dart. Do not edit.
// This example generator supplements Dust 0.3.1 with local Flame bindings.

import 'package:flame/components.dart';

import '../bridge/view_model_scope.dart';
import 'game_models.dart';

const _challengeViewModelKey = ViewModelKey(ChallengeViewModel.new);

extension GameViewModelAccess on Component {
  ChallengeViewModel readChallengeViewModel() =>
      readViewModel(_challengeViewModelKey);

  void watchChallengeViewModel(void Function(ChallengeViewModel) callback) =>
      watchViewModel(_challengeViewModelKey, callback);
}
''');
  });

  final invalidDeclarations = <String, String>{
    'class Required { Required(int id); }': 'no required parameters',
    'class Named { Named({required int id}); }': 'no required parameters',
    'class FactoryOnly { FactoryOnly.named(); }': 'unnamed constructor',
    'abstract class AbstractModel {}': 'must be concrete',
    'sealed class SealedModel {}': 'must be concrete',
    'class Generic<T> {}': 'must not have type parameters',
    'class _Private {}': 'must be public',
    'enum Model { value }': 'require a concrete class',
  };
  for (final entry in invalidDeclarations.entries) {
    test('rejects unsupported declaration ${entry.key}', () {
      expect(
        () => generateBindings('@ViewModel()\n${entry.key}'),
        throwsA(
          isA<FormatException>().having(
            (error) => error.message,
            'message',
            contains(entry.value),
          ),
        ),
      );
    });
  }

  test('reports syntax errors and a missing annotated model', () {
    expect(
      () => generateBindings('@ViewModel() class Broken {'),
      throwsA(
        isA<FormatException>().having(
          (error) => error.message,
          'message',
          contains('lib/state/game_models.dart:1:'),
        ),
      ),
    );
    expect(
      () => generateBindings('class Plain {}'),
      throwsA(
        isA<FormatException>().having(
          (error) => error.message,
          'message',
          contains('No @ViewModel classes found'),
        ),
      ),
    );
  });

  test('rejects model names that would produce duplicate keys', () {
    expect(
      () => generateBindings('''
@ViewModel() class Example {}
@ViewModel() class example {}
'''),
      throwsA(
        isA<FormatException>().having(
          (error) => error.message,
          'message',
          contains('duplicate keys'),
        ),
      ),
    );
  });

  test(
    'CLI checks current, stale, and missing bindings without writing',
    () async {
      final directory = await Directory.systemTemp.createTemp(
        'flame-bindings-',
      );
      addTearDown(() => directory.delete(recursive: true));
      final source = File('${directory.path}/lib/state/game_models.dart');
      await source.parent.create(recursive: true);
      const declaration = '@ViewModel(state: CounterState) class Counter {}';
      await source.writeAsString(declaration);
      final output = File(
        '${directory.path}/lib/state/game_access.generated.dart',
      );
      final script = File('tool/generate.dart').absolute.path;
      Future<ProcessResult> run(List<String> arguments) => Process.run('dart', [
        script,
        ...arguments,
      ], workingDirectory: directory.path);

      final missing = await run(['--check', '--bindings-only']);
      expect(missing.exitCode, 1, reason: '${missing.stderr}');
      expect(await output.exists(), isFalse);

      final generated = await run(['--bindings-only']);
      expect(generated.exitCode, 0, reason: '${generated.stderr}');
      final expected = generateBindings(declaration);
      expect(await output.readAsString(), expected);
      final timestamp = DateTime.utc(2001);
      await output.setLastModified(timestamp);

      final current = await run(['--bindings-only', '--check']);
      expect(current.exitCode, 0, reason: '${current.stderr}');
      expect(await output.readAsString(), expected);
      expect((await output.lastModified()).toUtc(), timestamp);

      await output.writeAsString('// stale\n');
      await output.setLastModified(timestamp);
      final stale = await run(['--check', '--bindings-only']);
      expect(stale.exitCode, 1);
      expect(stale.stderr, contains('Run dart run tool/generate.dart'));
      expect(await output.readAsString(), '// stale\n');
      expect((await output.lastModified()).toUtc(), timestamp);

      final invalid = await run(['--unknown']);
      expect(invalid.exitCode, 64);
      expect(invalid.stderr, contains('[--check] [--bindings-only]'));
      expect(await output.readAsString(), '// stale\n');
    },
  );
}
