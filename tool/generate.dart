import 'dart:io';

import 'package:analyzer/dart/ast/ast.dart';
import 'package:analyzer/dart/analysis/utilities.dart';

const _sourcePath = 'lib/state/game_models.dart';
const _outputPath = 'lib/state/game_access.generated.dart';

Future<void> main(List<String> arguments) async {
  if (arguments.any(
    (argument) => argument != '--bindings-only' && argument != '--check',
  )) {
    stderr.writeln(
      'Usage: dart run tool/generate.dart [--check] [--bindings-only]',
    );
    exitCode = 64;
    return;
  }

  try {
    final check = arguments.contains('--check');
    final source = await File(_sourcePath).readAsString();
    final output = generateBindings(source, sourcePath: _sourcePath);
    final destination = File(_outputPath);
    if (check) {
      if (!await destination.exists() ||
          await destination.readAsString() != output) {
        stderr.writeln(
          '$_outputPath is missing or stale. Run dart run tool/generate.dart.',
        );
        exitCode = 1;
        return;
      }
      stdout.writeln('Checked $_outputPath');
    } else {
      await destination.writeAsString(output);
      stdout.writeln('Generated $_outputPath');
    }

    if (!arguments.contains('--bindings-only')) {
      final dust = await Process.start('dust', [
        check ? 'check' : 'build',
      ], mode: ProcessStartMode.inheritStdio);
      final result = await dust.exitCode;
      if (result != 0) {
        exitCode = result;
        return;
      }
    }
  } on FormatException catch (error) {
    stderr.writeln(error.message);
    exitCode = 1;
  } on FileSystemException catch (error) {
    stderr.writeln(error);
    exitCode = 1;
  } on ProcessException catch (error) {
    stderr.writeln(
      'Could not run Dust. Install Dust 0.3.1 and add it to PATH.',
    );
    stderr.writeln(error.message);
    exitCode = 1;
  }
}

/// Generates the example's Flame bindings from parsed ViewModel declarations.
String generateBindings(String source, {String sourcePath = _sourcePath}) {
  final parsed = parseString(
    content: source,
    path: sourcePath,
    throwIfDiagnostics: false,
  );
  if (parsed.errors.isNotEmpty) {
    final diagnostics = parsed.errors.map((error) {
      final location = parsed.lineInfo.getLocation(error.offset);
      return '$sourcePath:${location.lineNumber}: ${error.message}';
    });
    throw FormatException(diagnostics.join('\n'));
  }

  final names = <String>[];
  for (final declaration in parsed.unit.declarations) {
    if (!declaration.metadata.any(_isViewModel)) continue;
    if (declaration is! ClassDeclaration) {
      throw FormatException(
        '$sourcePath: @ViewModel bindings require a concrete class.',
      );
    }
    _validateClass(declaration, sourcePath);
    names.add(declaration.name.lexeme);
  }
  names.sort();
  if (names.isEmpty) {
    throw FormatException('$sourcePath: No @ViewModel classes found.');
  }
  if (names.toSet().length != names.length) {
    throw FormatException('$sourcePath: Duplicate @ViewModel class names.');
  }
  if (names.map(_keyName).toSet().length != names.length) {
    throw FormatException(
      '$sourcePath: ViewModel names create duplicate keys.',
    );
  }

  final output = StringBuffer(
    '''// Generated by tool/generate.dart. Do not edit.
// This example generator supplements Dust 0.3.1 with local Flame bindings.

import 'package:flame/components.dart';

import '../bridge/view_model_scope.dart';
import 'game_models.dart';

''',
  );
  for (final name in names) {
    final key = _keyName(name);
    final declaration = 'const $key = ViewModelKey($name.new);';
    if (declaration.length <= 80) {
      output.writeln(declaration);
    } else {
      output.writeln('const $key = ViewModelKey(');
      output.writeln('  $name.new,');
      output.writeln(');');
    }
  }
  output.writeln('\nextension GameViewModelAccess on Component {');
  for (final (index, name) in names.indexed) {
    if (index > 0) output.writeln();
    final key = _keyName(name);
    final readSignature = '  $name read$name() =>';
    final readBody = 'readViewModel($key);';
    if ('$readSignature $readBody'.length <= 80) {
      output.writeln('$readSignature $readBody');
    } else {
      output.writeln(readSignature);
      output.writeln('      $readBody');
    }
    output.writeln();
    output.writeln('  void watch$name(void Function($name) callback) =>');
    output.writeln('      watchViewModel($key, callback);');
  }
  output.writeln('}');
  return output.toString();
}

String _keyName(String name) =>
    '_${name[0].toLowerCase()}${name.substring(1)}Key';

bool _isViewModel(Annotation annotation) => switch (annotation.name) {
  SimpleIdentifier(:final name) => name == 'ViewModel',
  PrefixedIdentifier(:final identifier) => identifier.name == 'ViewModel',
  _ => false,
};

void _validateClass(ClassDeclaration declaration, String sourcePath) {
  final name = declaration.name.lexeme;
  final prefix = '$sourcePath: $name';
  if (name.startsWith('_')) {
    throw FormatException('$prefix must be public for standalone bindings.');
  }
  if (declaration.abstractKeyword != null ||
      declaration.sealedKeyword != null) {
    throw FormatException('$prefix must be concrete.');
  }
  if (declaration.typeParameters != null) {
    throw FormatException('$prefix must not have type parameters.');
  }
  final constructors = declaration.members.whereType<ConstructorDeclaration>();
  final unnamed = constructors.where((value) => value.name == null).firstOrNull;
  if (constructors.isNotEmpty && unnamed == null) {
    throw FormatException('$prefix needs an unnamed constructor.');
  }
  if (unnamed != null &&
      unnamed.parameters.parameters.any((parameter) => parameter.isRequired)) {
    throw FormatException(
      '$prefix needs an unnamed constructor with no required parameters. '
      'Declare its dependencies in a zero-argument factory for this example.',
    );
  }
}
